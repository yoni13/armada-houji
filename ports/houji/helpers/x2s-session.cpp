#include "common.hpp"
#include <iostream>
#include <pwd.h>

using namespace houji;
static constexpr auto HEADER = "# Generated by houji-x2s-session; session-specific X2s routing.\n";
static std::string session_mode(const fs::path &proc, uid_t uid) {
    bool game = false;
    for (const auto &item : fs::directory_iterator(proc)) {
        if (!digits(item.path().filename().string())) continue;
        struct stat st{};
        if (stat(item.path().c_str(), &st) || st.st_uid != uid) continue;
        try {
            auto exe = fs::canonical(item.path() / "exe").filename();
            if (exe == "kwin_wayland") return "desktop";
            if (exe == "gamescope" && argument(read(item.path() / "cmdline"), "--steam")) game = true;
        } catch (const std::exception &) {} // process exited during discovery
    }
    return game ? "game" : "";
}
static void replace_once(std::string &text, const std::string &from, const std::string &to) {
    auto position = text.find(from);
    if (position == std::string::npos || text.find(from, position + from.size()) != std::string::npos)
        throw std::runtime_error("Unexpected X2s profile layout");
    text.replace(position, from.size(), to);
}
static void apply(const std::string &mode, const fs::path &source, const fs::path &output,
                  const std::string &systemctl) {
    auto text = read(source);
    if (mode == "desktop") {
        replace_once(text, "  - group: gamepad\n", "  - group: gamepad\n    ignore: true\n");
        replace_once(text, "target_devices:\n  - deck-uhid\n  - keyboard\n", "target_devices:\n  - keyboard\n");
    }
    text = HEADER + text;
    fs::create_directories(output.parent_path());
    if (fs::exists(output) && read(output).rfind(HEADER, 0) != 0)
        throw std::runtime_error("X2s override contains a custom configuration");
    atomic_write(output, text);
    run({systemctl, "restart", "inputplumber.service"}, 10);
}
int main(int argc, char **argv) {
    try {
        Options options(argc, argv, {"--proc", "--uid", "--source", "--output", "--systemctl", "--interval-ms"});
        auto *user = getpwnam("armada");
        const std::string uid_text = options.get("--uid", user ? std::to_string(user->pw_uid) : "");
        if (!digits(uid_text)) throw std::runtime_error("Armada user unavailable");
        uid_t uid = std::stoul(uid_text);
        const fs::path proc = options.get("--proc", "/proc");
        const fs::path source = options.get("--source", "/usr/share/inputplumber/devices/11-gamesir-x2s.yaml");
        const fs::path output = options.get("--output", "/etc/inputplumber/devices.d/10-houji-x2s-session.yaml");
        const auto systemctl = options.get("--systemctl", "/usr/bin/systemctl");
        const auto interval = options.interval(1000);
        signals(); std::string applied; bool failed = false;
        do {
            try {
                auto mode = session_mode(proc, uid);
                if (!mode.empty() && mode != applied) {
                    apply(mode, source, output, systemctl);
                    applied = mode; failed = false;
                    std::cout << "X2s routing: " << (mode == "desktop" ? "physical gamepad in Plasma" : "Steam Deck mapping in Game Mode") << std::endl;
                }
            } catch (const std::exception &e) {
                if (!failed) std::cerr << "X2s routing unavailable; will retry: " << e.what() << '\n';
                failed = true;
                if (options.once) return 1;
            }
            if (options.once) break;
            pause(failed ? 5000 : interval);
        } while (!stopped);
        return 0;
    } catch (const std::exception &e) { std::cerr << e.what() << '\n'; return 1; }
}
